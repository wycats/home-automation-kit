/* Host framework doubles around extracted admission and finish functions. */
#include <assert.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
typedef uint64_t u64;
#include "hantro_h264_enc_ref.h"
#define HANTRO_MODE_H264_ENC 1
#define HANTRO_MODE_JPEG_ENC 2
#define V4L2_BUF_FLAG_LAST 4U
#define WARN_ON(x) (!!(x))
enum vb2_buffer_state { VB2_BUF_STATE_ERROR = 7 };
struct request_object { void *req; };
struct vb2_buffer { struct request_object req_obj; };
struct vb2_v4l2_buffer { struct vb2_buffer vb2_buf; unsigned sequence, flags; };
struct hantro_enc_buf { struct vb2_v4l2_buffer base; struct hantro_h264_ref h264_ref; };
struct format { int codec_mode; };
struct hantro_dev { int irqlock; void *m2m_dev; };
struct hantro_ctx {
    struct hantro_dev *dev;
    bool is_encoder;
    struct format *vpu_dst_fmt;
    struct { void *m2m_ctx; } fh;
    int ctrl_handler;
    unsigned sequence_out, sequence_cap;
};
static struct hantro_enc_buf source_buf, dst_buf;
static struct hantro_h264_ref older_ref;
static struct hantro_h264_ref_domain refs;
static struct hantro_ctx *current;
static struct hantro_dev dev;
static struct format fmt;
static int lock_depth, request_done, pair_done, bypass, events, stopped;
static bool draining, free_at_finish;
static const int hantro_eos_event;
#define spin_lock_irqsave(l, f) do { assert((l) == &dev.irqlock); assert(!lock_depth); lock_depth++; (f) = 0; } while (0)
#define spin_unlock_irqrestore(l, f) do { (void)(l); (void)(f); assert(lock_depth == 1); lock_depth--; } while (0)
static struct vb2_v4l2_buffer *hantro_get_src_buf(struct hantro_ctx *ctx)
{ assert(ctx == current); return &source_buf.base; }
static struct vb2_v4l2_buffer *hantro_get_dst_buf(struct hantro_ctx *ctx)
{ assert(ctx == current); return &dst_buf.base; }
static struct hantro_enc_buf *hantro_get_enc_buf(struct vb2_v4l2_buffer *buf)
{ assert(buf == &dst_buf.base); return &dst_buf; }
static struct vb2_v4l2_buffer *v4l2_m2m_next_src_buf(void *m)
{ assert(m == current); return &source_buf.base; }
static struct vb2_v4l2_buffer *v4l2_m2m_next_dst_buf(void *m)
{ assert(m == current); return &dst_buf.base; }
static bool v4l2_m2m_is_last_draining_src_buf(void *m, struct vb2_v4l2_buffer *src)
{ assert(m == current && src == &source_buf.base); return draining; }
static void v4l2_event_queue_fh(void *fh, const int *e)
{ assert(fh == &current->fh && e == &hantro_eos_event); events++; }
static void v4l2_m2m_mark_stopped(void *m)
{ assert(m == current); stopped++; }
static void v4l2_ctrl_request_complete(void *req, int *handler)
{
    assert(!lock_depth && req == source_buf.base.vb2_buf.req_obj.req);
    assert(handler == &current->ctrl_handler && ++request_done == 1);
    assert(!dst_buf.h264_ref.valid && older_ref.valid && refs.epoch == 1);
}
static void v4l2_m2m_buf_done_and_job_finish(void *mdev, void *m, enum vb2_buffer_state state)
{
    assert(mdev == &dev && m == current && state == VB2_BUF_STATE_ERROR);
    assert(!lock_depth && request_done == 1 && ++pair_done == 1);
    assert(source_buf.base.sequence + 1 == current->sequence_out);
    assert(dst_buf.base.sequence + 1 == current->sequence_cap);
    if (free_at_finish) { free(current); current = NULL; }
}
static void device_run(void *priv)
{
    assert(priv == current && !lock_depth);
    assert(!current->is_encoder || fmt.codec_mode != HANTRO_MODE_H264_ENC);
    bypass++;
}
/* Real functions, including exact source license/attribution, generated by Python. */
#include "admission_subject.inc"

static void prepare(struct hantro_ctx *ctx, bool has_request)
{
    current = ctx;
    *ctx = (struct hantro_ctx){ .dev = &dev, .is_encoder = true,
        .vpu_dst_fmt = &fmt, .sequence_out = 11, .sequence_cap = 23 };
    ctx->fh.m2m_ctx = ctx; dev.m2m_dev = &dev;
    fmt.codec_mode = HANTRO_MODE_H264_ENC;
    request_done = pair_done = bypass = events = stopped = lock_depth = 0;
    draining = free_at_finish = false;
    memset(&source_buf, 0, sizeof(source_buf)); memset(&dst_buf, 0, sizeof(dst_buf));
    source_buf.base.vb2_buf.req_obj.req = has_request ? &source_buf : NULL;
    refs = (struct hantro_h264_ref_domain){ .epoch = 1 };
    assert(hantro_h264_ref_publish(&older_ref, &refs, 1, 1));
    assert(hantro_h264_ref_publish(&dst_buf.h264_ref, &refs, 1, 2));
}
int main(void)
{
    struct hantro_ctx ctx;
    /* Bounded repeated scheduler entries, with and without media requests. */
    for (unsigned i = 0; i < 64; i++) {
        prepare(&ctx, i % 2); draining = i % 3 == 0;
        hantro_device_run(&ctx);
        assert(request_done == 1 && pair_done == 1 && !bypass && !lock_depth);
        assert(events == (int)draining && stopped == (int)draining);
        assert(!!(dst_buf.base.flags & V4L2_BUF_FLAG_LAST) == draining);
    }
    /* Completion is a terminal boundary: ASan catches any later ctx access. */
    struct hantro_ctx *heap = malloc(sizeof(*heap)); assert(heap);
    prepare(heap, true); free_at_finish = true; hantro_device_run(heap);
    assert(!current && request_done == 1 && pair_done == 1);
    /* Preserve JPEG encoder and H264 decoder delegation without any cleanup. */
    for (unsigned i = 0; i < 2; i++) {
        prepare(&ctx, true);
        if (i) ctx.is_encoder = false; else fmt.codec_mode = HANTRO_MODE_JPEG_ENC;
        hantro_device_run(&ctx);
        assert(bypass == 1 && !request_done && !pair_done && dst_buf.h264_ref.valid);
    }
    puts("64 bounded H264 admission rejections, terminal ctx-free and 2 non-H264 delegation cases passed; no hardware or kernel framework execution.");
    return 0;
}
